"""Regenerate db/schema.sql from the SQLAlchemy models:  python scripts/dump_schema.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.models import Base  # noqa: E402

parts = ["-- Generated by scripts/dump_schema.py from app/models.py. The app also runs create_all() on startup.\n"]
for table in Base.metadata.sorted_tables:
    parts.append(str(CreateTable(table).compile(dialect=postgresql.dialect())).strip() + ";\n")
    for index in sorted(table.indexes, key=lambda i: i.name):
        parts.append(str(CreateIndex(index).compile(dialect=postgresql.dialect())).strip() + ";\n")
(ROOT / "db" / "schema.sql").write_text("\n".join(parts), encoding="utf-8")
print("wrote db/schema.sql")
